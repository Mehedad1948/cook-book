/** Regenerates content/recipes/index.ts from the files in the folder ("add a recipe = add one file"). */
import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "content", "recipes");
const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.replace(/\.ts$/, ""))
  .sort();

const ident = (s: string) => "r_" + s.replace(/-/g, "_");
const body =
  `// GENERATED by scripts/gen-index.ts (runs before dev/build). Do not edit.\n` +
  slugs.map((s) => `import ${ident(s)} from "./${s}";`).join("\n") +
  `\n\nexport const recipes = [${slugs.map(ident).join(", ")}];\n`;

const file = join(dir, "index.ts");
if (!existsSync(file) || readFileSync(file, "utf8") !== body) writeFileSync(file, body);
